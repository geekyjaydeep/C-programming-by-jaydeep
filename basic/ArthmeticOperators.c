#include<stdio.h>
int main(){
    int a = 100 , b = 10;
    printf("Sum of %i and %i = %i\n" , a, b , (a+b) );
    printf("Subtraction of %i and %i = %i\n" , a , b , (a-b));
    printf("Product of %i and %i = %i\n" , a, b , (a*b) );
    printf("Division of %i and %i = %i\n" , a, b , (a/b) );
    return 0 ; 
}